export function bagLine(count: number, lang: Lang) {
  if (lang === "ru") {
    const mod10 = count % 10
    const mod100 = count % 100
    const word =
      mod10 === 1 && mod100 !== 11
        ? "вещь"
        : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
          ? "вещи"
          : "вещей"
    return `В корзине ${count} ${word}. Доставка бесплатная.`
  }
  if (lang === "en") {
    const word = count === 1 ? "item" : "items"
    return `You have ${count} ${word} in your bag. Enjoy free shipping on your order.`
  }
  const uncovered: never = lang
  return uncovered
}

